#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md from package-lock.json + installed node_modules.
 * Lists every production (non-dev) third-party dependency with its declared SPDX
 * license, flags licenses outside a permissive allow-list, and exits non-zero when
 * `--check` is passed and the committed file is stale or a license is unreviewed.
 *
 * Usage:  node scripts/generate-third-party-notices.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');
const CHECK = process.argv.includes('--check');

// Licenses reviewed as compatible with distributing PkgDiet under MIT.
const PERMISSIVE = new Set([
  'MIT', 'MIT-0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0',
  'BlueOak-1.0.0', 'Unlicense', 'CC0-1.0', 'Python-2.0', 'CC-BY-4.0',
]);

function fail(msg) { console.error(`✗ ${msg}`); process.exit(1); }

let lock;
try { lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf8')); }
catch (err) { fail(`Cannot read package-lock.json: ${err.message}`); }

const normLicense = pkg => {
  const l = pkg.license ?? pkg.licenses;
  if (!l) return 'UNKNOWN';
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map(x => x.type || x).join(' OR ');
  return l.type || 'UNKNOWN';
};
const allPermissive = expr =>
  expr.split(/\s+(?:OR|AND)\s+|[()]/).map(s => s.trim()).filter(Boolean).every(id => PERMISSIVE.has(id));
const repoUrl = pkg => {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return r ? r.replace(/^git\+/, '').replace(/\.git$/, '') : '';
};

const rows = [];
const missing = [];
for (const [key, entry] of Object.entries(lock.packages || {})) {
  if (!key || key.startsWith('packages/') || entry.dev || entry.link) continue;
  const manifestPath = path.join(ROOT, key, 'package.json');
  let manifest = {};
  try { manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8')); }
  catch { manifest = { name: key.replace(/^.*node_modules\//, ''), version: entry.version, license: entry.license }; missing.push(key); }
  rows.push({
    name: manifest.name || key.replace(/^.*node_modules\//, ''),
    version: manifest.version || entry.version || '',
    license: normLicense(manifest),
    repo: repoUrl(manifest),
  });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const unreviewed = rows.filter(r => !allPermissive(r.license));
const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] || 0) + 1;

const lines = [
  '# Third-party notices',
  '',
  'PkgDiet is distributed under the [MIT License](LICENSE). The published packages declare the',
  'production dependencies below; they are installed by your package manager and keep their own',
  'licenses and copyright notices. This file is generated by',
  '`node scripts/generate-third-party-notices.mjs` from `package-lock.json` — do not edit by hand.',
  '',
  `Production dependencies listed: **${rows.length}**. License summary: ` +
    Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(', ') + '.',
  '',
  unreviewed.length === 0
    ? 'All listed licenses are in the project\'s permissive allow-list (no copyleft or unknown licenses).'
    : `**Needs review:** ${unreviewed.map(r => `${r.name}@${r.version} (${r.license})`).join(', ')}.`,
  '',
  'Curated alternatives data (`packages/core/data/alternatives.json`) is original project content.',
  'Vulnerability data is fetched at run time from OSV.dev and is **not** redistributed in this repository.',
  '',
  '| Package | Version | License | Source |',
  '|---|---|---|---|',
  ...rows.map(r => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo || '—'} |`),
  '',
  'Names of third-party products are used only to identify compatible tools; see [LEGAL.md](LEGAL.md).',
  '',
];
const next = lines.join('\n');

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (unreviewed.length) fail(`Unreviewed production licenses: ${unreviewed.map(r => `${r.name} (${r.license})`).join(', ')}`);
  if (current !== next) fail('THIRD_PARTY_NOTICES.md is stale — run: node scripts/generate-third-party-notices.mjs');
  console.log('✓ THIRD_PARTY_NOTICES.md is current and all licenses are permissive.');
} else {
  fs.writeFileSync(OUT, next);
  console.log(`✓ Wrote ${path.relative(ROOT, OUT)} (${rows.length} packages${missing.length ? `, ${missing.length} not installed locally` : ''}).`);
  if (unreviewed.length) console.warn(`⚠ Needs review: ${unreviewed.map(r => `${r.name} (${r.license})`).join(', ')}`);
}
